// Helper functions
export function getCosmeticsByType(type) {
  return COSMETICS.filter(c => c.type === type)
}

export function getCosmeticById(id) {
  return COSMETICS.find(c => c.id === id)
}

export function getDefaultCosmetic(type) {
  return COSMETICS.find(c => c.type === type && c.unlockCriteria?.default)
}