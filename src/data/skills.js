// Helper: get skills by region
export function getSkillsByRegion(regionId) {
  return SKILLS.filter(s => s.regionId === regionId)
}

// Helper: get skill by ID
export function getSkillById(id) {
  return SKILLS.find(s => s.id === id)
}

// Helper: get prerequisite chain for a skill
export function getPrerequisiteChain(skillId, visited = new Set()) {
  const skill = getSkillById(skillId)
  if (!skill || visited.has(skillId)) return []
  visited.add(skillId)
  const chain = []
  for (const prereq of skill.prerequisites) {
    chain.push(prereq)
    chain.push(...getPrerequisiteChain(prereq, visited))
  }
  return chain
}